#!/usr/bin/env node
/**
 * check-component-count.js
 *
 * The number "how many components does Atelier ship" drifted four ways with
 * nothing saying which was which: README.md's hand-typed "31" (a raw
 * directory count under libs/<fw>/src/lib/, including `foundation` and
 * `showcase`, which are not components), plan/design-status.md's 29 (Figma
 * masters — `radio` and `radio-group` are two masters), docs/src/data/
 * components.ts's 28 (catalogued composites — `AtlTab`, `AtlMenuItem`,
 * `AtlCardHeader`, `AtlAvatarGroup`, `AtlAccordionItem` and `radio` correctly
 * have no entry either), and its Inputs category's 8. 28 and 29 are both
 * correct for what they count; 31 was simply wrong. tasks/todo.md and the
 * owner's 2026-09-10 decision are the record of that.
 *
 * This gate is the mechanical half of the fix: nothing previously caught a
 * hand-typed component count going stale, which is exactly how it drifted
 * four times. It does not decide which number is right — it only requires
 * that every bare "<number> component(s)" in participant-facing material be
 * either provably derived (a code expression, not a literal digit — so it
 * never matches the regex below at all) or named in COMPONENT_COUNT_EXEMPT
 * (tools/scripts/lib/allowlists.js) with a written reason. A dated historical
 * record ("on 2026-08-26 this library's 29 components were…") is the
 * legitimate allowlist case named in the task that added this gate; a number
 * stated together with what it counts and a citation to the live source is
 * the other.
 *
 * Checks:
 *   [BARE-COUNT]     A scanned file contains "<digits> [word] [word]
 *                     component(s)" (case-insensitive; a fixed-length
 *                     negative lookbehind excludes "Angular 22 component
 *                     library" / "React 19 component" / "Vue 3 component" —
 *                     those numbers are framework versions, not counts) with
 *                     no matching COMPONENT_COUNT_EXEMPT entry.
 *   [DEAD-ALLOWLIST]  A COMPONENT_COUNT_EXEMPT entry matched nothing this run
 *                     — the line it named moved, was fixed, or the file no
 *                     longer exists. Same [STALE-EXEMPTION] hygiene as the
 *                     repo's other allowlists: an unused exemption is itself
 *                     a bug, so it fails loudly instead of rotting silently.
 *
 * Scope — deliberately NOT every file that mentions a component count:
 *   - A file that opens with a "GENERATED by" marker (the repo's existing
 *     convention — see plan/design-status.md's own header) is skipped
 *     entirely. Its numbers are derived by construction; re-litigating them
 *     here would just duplicate the generator's own gate (check:design-status)
 *     instead of catching a hand-typed count.
 *   - docs/src/data/components.ts is not scanned. It IS the source
 *     (COMPONENT_CATEGORIES / ALL_COMPONENTS.length) every other site here
 *     derives from or cites — there is nothing to check it against, and it is
 *     out of this task's ownership besides (another agent's file).
 *   - plan/adr/**, plan/figma.md and plan/research/** are not scanned. ADRs
 *     are immutable decision records (AGENTS.md) already governed by
 *     check-adr-refs; a count inside one is a historical fact, not a live
 *     claim this gate exists to keep fresh. plan/figma.md and the research
 *     notebooks are out of this task's ownership.
 *   - skills/figma-workspace-architect/** is not scanned. Its "150
 *     components" / "200 components" mentions are arbitrary sizing
 *     thresholds for a USER'S OWN Figma library (a generic, reusable skill) —
 *     a different fact entirely from "how many components does Atelier
 *     ship," and not a drift risk this gate exists for. Scanning it would
 *     need a dozen-plus allowlist entries for content that can never be
 *     "wrong" in the sense this gate cares about.
 *
 * Run via:  node tools/scripts/check-component-count.js
 *           (or  npm run check:component-count)
 */
'use strict';

const fs = require('fs');
const path = require('path');
const {
  COMPONENT_COUNT_EXEMPT,
  componentCountKey,
} = require('./lib/allowlists');

const ROOT = path.resolve(__dirname, '../..');

/**
 * Bare "<number> [word] [word] component(s)" — a hand-typed count claim.
 * Case-insensitive. Up to two filler words are allowed between the number and
 * "component(s)" (e.g. "28 catalogued components", "22 of 28 component-sets").
 * The fixed-length negative lookbehinds exclude the one recurring false-
 * positive class in this repo's own README: framework version numbers
 * directly followed by the word "component" ("Angular 22 component library",
 * "React 19 component library", "Vue 3 component library").
 */
const COUNT_RE =
  /(?<!Angular )(?<!React )(?<!Vue )\b\d{1,4}\s+(?:[a-zA-Z-]+\s+){0,2}components?\b/gi;

/** Participant-facing surfaces this gate scans. See the header comment above
 *  for what is deliberately excluded and why. */
const SCAN_ROOTS = [
  { files: ['README.md'] },
  { dir: 'docs/src/pages', exts: ['.astro'] },
  { files: ['schulung-2tage-agenda.md'] },
  { dir: 'workshop/briefs', exts: ['.md'] },
  { dir: 'talk', exts: ['.md'] },
  { dir: 'skills/atelier-design', exts: ['.md'] },
  { dir: 'skills/artboard-bridge', exts: ['.md'] },
  {
    files: [
      'plan/ai-readiness.md',
      'plan/big-picture.md',
      'plan/design-principles.md',
      'plan/design-skills-blueprint.md',
      'plan/design-status.md',
      'plan/figma-component-checklist.md',
      'plan/roadmap.md',
    ],
  },
];

/** A file opening with a "GENERATED by" marker is machine-written; skip it
 *  outright rather than allowlisting every line in it (see header comment). */
function isGenerated(content) {
  return /generated by/i.test(content.slice(0, 1000));
}

function walk(dir, exts) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full, exts));
    else if (exts.some((ext) => entry.name.endsWith(ext))) out.push(full);
  }
  return out;
}

function scanFiles() {
  const files = [];
  for (const root of SCAN_ROOTS) {
    if (root.files) files.push(...root.files.map((f) => path.join(ROOT, f)));
    if (root.dir) files.push(...walk(path.join(ROOT, root.dir), root.exts));
  }
  return [...new Set(files)].filter((f) => fs.existsSync(f));
}

const errors = [];
const used = new Set();

for (const file of scanFiles()) {
  const rel = path.relative(ROOT, file);
  const content = fs.readFileSync(file, 'utf8');
  if (isGenerated(content)) continue;

  const lines = content.split('\n');
  lines.forEach((line, i) => {
    const match = line.match(COUNT_RE);
    if (!match) return;

    let prevLine = '';
    for (let j = i - 1; j >= 0; j -= 1) {
      if (lines[j].trim() !== '') {
        prevLine = lines[j];
        break;
      }
    }
    const key = componentCountKey(rel, prevLine, line);
    if (COMPONENT_COUNT_EXEMPT.has(key)) {
      used.add(key);
      return;
    }
    errors.push(
      `[BARE-COUNT] ${rel}:${i + 1} states "${match[0].trim()}" with no matching COMPONENT_COUNT_EXEMPT ` +
        'entry. Either derive the number (compute it from docs/src/data/components.ts or another live ' +
        'source instead of typing it) — or, if it is a genuine, permanent exception (a dated historical ' +
        'record, or a number stated together with what it counts and a citation to its source), add an ' +
        'entry to COMPONENT_COUNT_EXEMPT in tools/scripts/lib/allowlists.js with a written reason, keyed ' +
        'like this:\n' +
        '      componentCountKey(\n' +
        `        ${JSON.stringify(rel)},\n` +
        `        ${JSON.stringify(prevLine.trim())},\n` +
        `        ${JSON.stringify(line.trim())},\n` +
        '      )',
    );
  });
}

// [DEAD-ALLOWLIST]: an exemption that matched nothing this run has rotted —
// the line it named moved, was fixed, or the file is gone. Same hygiene the
// repo's other content-keyed allowlist (SCAFFOLD_PORT_EXEMPT) is held to.
for (const key of COMPONENT_COUNT_EXEMPT.keys()) {
  if (!used.has(key)) {
    errors.push(
      `[DEAD-ALLOWLIST] COMPONENT_COUNT_EXEMPT has an entry that matched nothing this run:\n${key}\n` +
        'The citation this entry named no longer exists at that exact text — fix the (now stale) key, or ' +
        'remove the entry, in tools/scripts/lib/allowlists.js.',
    );
  }
}

if (errors.length > 0) {
  errors.forEach((e) => console.error(`✗ ${e}`));
  console.error(`\n${errors.length} issue(s) found.`);
  process.exit(1);
} else {
  console.log(
    `✓ No bare hand-typed component counts outside COMPONENT_COUNT_EXEMPT ` +
      `(${COMPONENT_COUNT_EXEMPT.size} allowlisted, all in use)`,
  );
}
